#!/usr/bin/env python3
"""Read-only GraphQL gateway over the indexer event corpus (issue #1444).

Stdlib only. Serves a documented subset of GraphQL (queries with nested
selection sets and literal arguments) over the JSON-lines corpus described in
docs/compliance-report.md. Every query is statically analysed before it runs:
depth and complexity limits bound the work any single query can force.

Read-only by construction: the schema has no Mutation or Subscription type and
the executor rejects any operation other than `query`; the corpus is opened
read-only and never written.

Usage:
  gateway.py schema [--check FILE]      print (or verify) the SDL
  gateway.py query CORPUS 'QUERY'       run one query, print JSON
"""

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

MAX_DEPTH = 3
MAX_COMPLEXITY = 1000
DEFAULT_LIMIT = 10
MAX_LIMIT = 100

# Field name -> GraphQL scalar. Mirrors the corpus record schema in
# tools/compliance-report/generate.py; `check_in_sync` enforces the event
# types stay aligned with its KNOWN_TYPES.
EVENT_FIELDS = {
    "contract_id": "String",
    "ledger": "Int",
    "event_index": "Int",
    "type": "String",
    "wallet": "String",
    "score": "Int",
}


class GatewayError(Exception):
    pass


def known_types():
    path = Path(__file__).resolve().parents[1] / "compliance-report" / "generate.py"
    spec = importlib.util.spec_from_file_location("compliance_generate", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return sorted(mod.KNOWN_TYPES)


def sdl():
    lines = ["# Generated by tools/graphql-gateway/gateway.py schema. Do not edit.",
             "# Event types: " + ", ".join(known_types()), "", "type Event {"]
    lines += [f"  {n}: {t}" for n, t in sorted(EVENT_FIELDS.items())]
    lines += ["  related(limit: Int): [Event!]!", "}", "", "type Query {",
              "  events(type: String, limit: Int, offset: Int): [Event!]!",
              "  eventCount(type: String): Int!", "}", ""]
    return "\n".join(lines)


_TOKEN = re.compile(r'\s*(?:(?P<p>[{}():,])|(?P<s>"[^"]*")|(?P<i>-?\d+)|(?P<n>[A-Za-z_]\w*))')


def tokenize(text):
    pos, out = 0, []
    text = text.rstrip()
    while pos < len(text):
        m = _TOKEN.match(text, pos)
        if not m:
            raise GatewayError(f"syntax error at offset {pos}")
        pos = m.end()
        kind = m.lastgroup
        val = m.group(kind)
        if kind == "s":
            val = val[1:-1]
        elif kind == "i":
            val = int(val)
        if kind != "p" or val != ",":
            out.append((kind, val))
    return out


def parse(text):
    toks = tokenize(text)
    i = 0

    def peek():
        return toks[i] if i < len(toks) else (None, None)

    def take(kind=None, val=None):
        nonlocal i
        k, v = peek()
        if k is None or (kind and k != kind) or (val is not None and v != val):
            raise GatewayError(f"syntax error: unexpected {v!r}")
        i += 1
        return v

    def selection():
        take("p", "{")
        fields = []
        while peek() != ("p", "}"):
            name = take("n")
            args = {}
            if peek() == ("p", "("):
                take("p", "(")
                while peek() != ("p", ")"):
                    key = take("n")
                    take("p", ":")
                    k, v = peek()
                    if k not in ("s", "i"):
                        raise GatewayError(f"argument {key} must be a literal")
                    take()
                    args[key] = v
                take("p", ")")
            sub = selection() if peek() == ("p", "{") else None
            fields.append({"name": name, "args": args, "sub": sub})
        take("p", "}")
        if not fields:
            raise GatewayError("empty selection set")
        return fields

    if peek() == ("n", "query"):
        take()
    elif peek()[0] == "n":
        raise GatewayError(f"operation {peek()[1]!r} is not supported: gateway is read-only")
    doc = selection()
    if peek()[0] is not None:
        raise GatewayError("only a single query operation is supported")
    return doc


def _limit(args):
    n = args.get("limit", DEFAULT_LIMIT)
    if not isinstance(n, int) or n < 0 or n > MAX_LIMIT:
        raise GatewayError(f"limit must be an integer in 0..{MAX_LIMIT}")
    return n


def analyse(fields, depth=1, parent="Query"):
    """Return (max_depth, complexity). Raises GatewayError past either limit."""
    if depth > MAX_DEPTH:
        raise GatewayError(f"query depth exceeds limit of {MAX_DEPTH}")
    total, deepest = 0, depth
    for f in fields:
        name = f["name"]
        if parent == "Query":
            if name not in ("events", "eventCount"):
                raise GatewayError(f"unknown field Query.{name}")
        elif name != "related" and name not in EVENT_FIELDS:
            raise GatewayError(f"unknown field Event.{name}")
        if name in ("events", "related"):
            if not f["sub"]:
                raise GatewayError(f"{name} requires a selection set")
            sub_depth, sub_cost = analyse(f["sub"], depth + 1, "Event")
            total += 1 + _limit(f["args"]) * sub_cost
            deepest = max(deepest, sub_depth)
        else:
            if f["sub"]:
                raise GatewayError(f"{name} is a scalar and takes no selection set")
            total += 1
    if total > MAX_COMPLEXITY:
        raise GatewayError(f"query complexity {total} exceeds limit of {MAX_COMPLEXITY}")
    return deepest, total


def load_events(path):
    with open(path, "r", encoding="utf-8") as fh:  # read-only
        return [json.loads(l) for l in fh if l.strip()]


def execute(events, text):
    doc = parse(text)
    analyse(doc)
    by_ledger = {}
    for e in events:
        by_ledger.setdefault(e.get("ledger"), []).append(e)

    def project(ev, sub):
        row = {}
        for f in sub:
            if f["name"] == "related":
                peers = [p for p in by_ledger.get(ev.get("ledger"), []) if p is not ev]
                row["related"] = [project(p, f["sub"]) for p in peers[:_limit(f["args"])]]
            else:
                row[f["name"]] = ev.get(f["name"])
        return row

    out = {}
    for f in doc:
        rows = [e for e in events if f["args"].get("type") in (None, e.get("type"))]
        if f["name"] == "eventCount":
            out["eventCount"] = len(rows)
        else:
            off = f["args"].get("offset", 0)
            page = rows[off:off + _limit(f["args"])]
            out["events"] = [project(e, f["sub"]) for e in page]
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("schema")
    s.add_argument("--check")
    q = sub.add_parser("query")
    q.add_argument("corpus")
    q.add_argument("query")
    a = ap.parse_args(argv)
    if a.cmd == "schema":
        text = sdl()
        if a.check:
            if Path(a.check).read_text(encoding="utf-8") != text:
                print(f"{a.check} is out of sync with the event definitions", file=sys.stderr)
                return 1
            return 0
        sys.stdout.write(text)
        return 0
    try:
        print(json.dumps({"data": execute(load_events(a.corpus), a.query)}, sort_keys=True))
    except GatewayError as e:
        print(json.dumps({"errors": [{"message": str(e)}]}))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
